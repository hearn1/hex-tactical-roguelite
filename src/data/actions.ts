import type { AbilityKey } from "./abilities.ts";

export type ActionTiming =
  | "action"
  | "bonus_action"
  | "reaction"
  | "free"
  | "passive"
  | "triggered_passive"
  | "attack_action_modifier"
  | "monster_special";

export const VALID_ACTION_TIMINGS: ReadonlySet<ActionTiming> = new Set([
  "action",
  "bonus_action",
  "reaction",
  "free",
  "passive",
  "triggered_passive",
  "attack_action_modifier",
  "monster_special",
]);

export interface ConditionApply {
  id: string;
  duration: number;
  save?: { stat: AbilityKey; dc: number };
}

export interface ActionDef {
  id: string;
  displayName: string;
  description: string;
  source: "class" | "item" | "enemy";
  targetType: "enemy" | "ally" | "self" | "ally_or_self";
  range: number;
  /**
   * When this action can be used in the turn structure. Omitted entries default to "action"
   * for backward compatibility (#503).
   */
  timing?: ActionTiming;
  accuracyStat?: AbilityKey;
  isCantrip?: boolean;
  charges?: number;
  /**
   * Resource the action draws on (#118). "cantrip"/"martial" are unlimited; "spell_slot" consumes
   * the caster's per-Long-Rest spell slots. Untagged actions behave as unlimited.
   */
  resourceType?: "cantrip" | "spell_slot" | "martial";
  /** Spell slots consumed per cast when `resourceType` is "spell_slot" (defaults to 1). */
  slotCost?: number;
  /** Nominal spell level, metadata for display/future scaling. */
  spellLevel?: number;
  /** Sorcery Points consumed per cast (Sorcerer Metamagic actions). */
  sorceryPointCost?: number;
  /** Ki points consumed per cast (Monk actions). */
  kiPointCost?: number;
  effect:
    | { type: "damage"; formula: string; applyCondition?: ConditionApply; targetMode?: "single" | "primary_plus_adjacent" | "aoe_around_caster" | "aoe_radius"; radius?: number; bonusDiceOnFlanking?: string; pushDistance?: number }
    | { type: "heal"; formula: string; targetMode?: "single" | "aoe_around_caster" | "aoe_radius"; radius?: number }
    | { type: "applyCondition"; conditionId: string; duration: number; targetMode?: "single" | "aoe_around_caster" | "aoe_radius"; radius?: number }
    | { type: "removeConditions" }
    | { type: "lineDamage"; formula: string; lineRange: number }
    | { type: "counterTelegraph" }
    /** Grants the caster one additional standard action this turn (e.g. Action Surge). */
    | { type: "grantExtraAction" }
    /** Data-level marker for attack_action_modifier features (e.g. Extra Attack). No runtime resolution needed. */
    | { type: "marker" };
}

